    fun find(code: String): CurrencyInfo {
        return currencyMap[code.uppercase()] ?: CurrencyInfo(
            code = code.uppercase(),
            name = code.uppercase(),
            symbol = code.uppercase(),
            countryCode = code.take(2).uppercase(),
            flagEmoji = flagFromCountryCode(code.take(2))
        )
    }

